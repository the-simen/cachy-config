#!/usr/bin/env python3
"""Generate a dialog(1) DIALOGRC from the live Noctalia palette.

Reads ~/.config/noctalia/colors.json (flat .m* hex map written by Noctalia),
quantizes each used role to the nearest of dialog's 16 named colors
(DIALOGRC understands names only, no hex/256), and writes a runtime config.

Usage:
    generate-dialogrc.py [colors.json] [output]

Defaults: ~/.config/noctalia/colors.json -> ~/.config/dialog/noctalia
Exit 2 when colors.json is missing/unreadable (caller should use the
tracked dialog/noctalia-default fallback instead).
"""
import json
import sys
from pathlib import Path

HOME = Path.home()
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HOME / ".config/noctalia/colors.json"
DST = Path(sys.argv[2]) if len(sys.argv) > 2 else HOME / ".config/dialog/noctalia"

# 16 colors dialog can address: 8 bases + bright (bold) variants.
BASE = {
    "BLACK": (0, 0, 0),
    "RED": (170, 0, 0),
    "GREEN": (0, 170, 0),
    "YELLOW": (170, 85, 0),
    "BLUE": (0, 0, 170),
    "MAGENTA": (170, 0, 170),
    "CYAN": (0, 170, 170),
    "WHITE": (170, 170, 170),
}
BRIGHT = {
    "BLACK": (85, 85, 85),
    "RED": (255, 85, 85),
    "GREEN": (85, 255, 85),
    "YELLOW": (255, 255, 85),
    "BLUE": (85, 85, 255),
    "MAGENTA": (255, 85, 255),
    "CYAN": (85, 255, 255),
    "WHITE": (255, 255, 255),
}


def parse_hex(s):
    s = s.strip().lstrip("#")
    if len(s) == 3:
        s = "".join(c * 2 for c in s)
    return int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16)


# Fills (title/button/selection backgrounds) are quantized to the dark
# base colors only: no WHITE, no bright — highlights stay dark, distinct
# from the (near-black) terminal background. Foregrounds use the full set.
DARK = {k: v for k, v in BASE.items() if k != "WHITE"}
FULL = [(n, BASE[n], False) for n in BASE] + [(n, BRIGHT[n], True) for n in BRIGHT]


def dist(a, b):
    dr, dg, db = a[0] - b[0], a[1] - b[1], a[2] - b[2]
    return 2 * dr * dr + 4 * dg * dg + 3 * db * db


def nearest(hex_color, table=None):
    """-> (NAME, bold_bool): closest color from table (default: all 16)."""
    try:
        rgb = parse_hex(hex_color)
    except (ValueError, AttributeError):
        return "WHITE", False
    table = FULL if table is None else [(n, DARK[n], False) for n in DARK]
    return min(table, key=lambda e: dist(rgb, e[1]))[0::2]


def main():
    try:
        palette = json.loads(SRC.read_text())
    except (OSError, ValueError) as e:
        print(f"generate-dialogrc: cannot read {SRC}: {e}", file=sys.stderr)
        return 2

    get = lambda k, fb="#ffffff": palette.get(k, fb)
    keys = {
        "mSurface", "mOnSurface", "mOnSurfaceVariant", "mPrimary",
        "mOnPrimary", "mSecondary", "mOnSecondary", "mTertiary",
        "mOnTertiary", "mError", "mShadow",
    }
    fgc = {k: nearest(get(k)) for k in keys}          # foregrounds: full range
    bgc = {k: nearest(get(k), DARK) for k in keys}    # fills: dark bases only
    dfc = bgc  # dark-constrained foregrounds (borders, arrows): same table

    def rc(fg_key, bg="DEFAULT", fg_dark=False):
        # Backgrounds default to the terminal's own background (SGR 49),
        # so the UI melts into the terminal. Only accents pass an explicit
        # dark fill. Foregrounds are quantized theme colors.
        fg, fb = (dfc if fg_dark else fgc)[fg_key]
        return f"({fg},{bg},{'ON' if fb else 'OFF'})"

    ACC_BG = bgc["mPrimary"][0]  # dark-constrained accent fill (e.g. CYAN)

    # Every widget dialog(1) can draw is covered: anything left unset falls
    # back to compiled-in white defaults (white menu rows, etc.).
    ACC, ONACC = "mPrimary", "mOnPrimary"   # main accent + its foreground
    lines = [
        "# Auto-generated by config-manager from the live Noctalia palette.",
        "# Do not edit: re-rendered on every launch. See dialog/noctalia-default.",
        "use_colors = ON",
        "use_shadow = OFF",
        "use_scrollbar = OFF",
        f"screen_color = {rc('mOnSurfaceVariant')}",
        f"shadow_color = {rc('mShadow')}",
        f"dialog_color = {rc('mOnSurface')}",
        f"title_color = {rc(ONACC, ACC_BG)}",
        f"border_color = {rc(ACC, fg_dark=True)}",
        f"border2_color = {rc(ACC, fg_dark=True)}",
        f"button_active_color = {rc(ONACC, ACC_BG)}",
        f"button_key_active_color = {rc('mOnTertiary', ACC_BG)}",
        f"button_label_active_color = {rc(ONACC, ACC_BG)}",
        f"button_inactive_color = {rc('mOnSurface')}",
        f"button_key_inactive_color = {rc('mSecondary')}",
        f"button_label_inactive_color = {rc('mOnSurface')}",
        f"inputbox_color = {rc('mOnSurface')}",
        f"inputbox_border_color = {rc('mOnSurface')}",
        f"inputbox_border2_color = {rc(ACC, fg_dark=True)}",
        f"searchbox_color = {rc('mOnSurface')}",
        f"searchbox_title_color = {rc(ONACC, ACC_BG)}",
        f"searchbox_border_color = {rc(ACC, fg_dark=True)}",
        f"searchbox_border2_color = {rc(ACC, fg_dark=True)}",
        f"position_indicator_color = {rc(ONACC, ACC_BG)}",
        f"menubox_color = {rc('mOnSurface')}",
        f"menubox_border_color = {rc(ACC, fg_dark=True)}",
        f"menubox_border2_color = {rc(ACC, fg_dark=True)}",
        f"item_color = {rc('mOnSurface')}",
        f"item_selected_color = {rc(ONACC, ACC_BG)}",
        f"tag_color = {rc('mTertiary')}",
        f"tag_selected_color = {rc(ONACC, ACC_BG)}",
        f"tag_key_color = {rc('mSecondary')}",
        f"tag_key_selected_color = {rc(ONACC, ACC_BG)}",
        f"check_color = {rc('mOnSurface')}",
        f"check_selected_color = {rc(ONACC, ACC_BG)}",
        f"uarrow_color = {rc('mSecondary', fg_dark=True)}",
        f"darrow_color = {rc('mSecondary', fg_dark=True)}",
        f"itemhelp_color = {rc('mOnSurfaceVariant')}",
        f"form_active_text_color = {rc(ONACC, ACC_BG)}",
        f"form_text_color = {rc('mOnSurface')}",
        f"form_item_readonly_color = {rc('mSecondary')}",
        f"gauge_color = {rc(ONACC, ACC_BG)}",
    ]
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text("\n".join(lines) + "\n")
    print(f"generate-dialogrc: wrote {DST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
